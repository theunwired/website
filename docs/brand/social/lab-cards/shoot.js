/* Redraws the Lab's link cards into assets/.
     npm i --prefix /tmp/pw playwright      (once, outside the repo)
     PLAYWRIGHT=/tmp/pw/node_modules/playwright node docs/brand/social/lab-cards/shoot.js
   Add CHROME=/path/to/chrome to use an installed Chromium instead of
   Playwright's own (npx playwright install chromium fetches that one).
   The engine is copied fresh from assets/lab.js each run, so the cards always
   match the queue the Lab runs. Re-scrape the pages in LinkedIn's Post
   Inspector after changing a card. */
const fs = require('fs');
const path = require('path');
const { chromium } = require(process.env.PLAYWRIGHT || 'playwright');

const here = __dirname;
const root = path.resolve(here, '../../../..');
const lab = fs.readFileSync(path.join(root, 'assets/lab.js'), 'utf8');
const from = lab.indexOf('  function mulberry32');
const to = lab.indexOf('  /* --------------------------------------------------- 01 Tolerance Lab */');
if (from < 0 || to < 0) throw new Error('could not find the engine in assets/lab.js');
fs.writeFileSync(path.join(here, 'engine.js'), '/* generated by shoot.js from assets/lab.js. Do not edit. */\n' + lab.slice(from, to));

const CARDS = { hub: 'og-lab.png', tolerance: 'og-lab-tolerance.png', handover: 'og-lab-handover.png', documents: 'og-lab-documents.png' };

(async () => {
  const browser = await chromium.launch(process.env.CHROME ? { executablePath: process.env.CHROME } : {});
  const page = await browser.newPage({ viewport: { width: 1200, height: 627 }, deviceScaleFactor: 1 });
  for (const k of Object.keys(CARDS)) {
    await page.goto('file://' + path.join(here, 'card.html') + '#' + k);
    await page.reload();
    await page.waitForSelector('body[data-ready]');
    await page.waitForTimeout(300);
    await page.screenshot({ path: path.join(root, 'assets', CARDS[k]) });
    console.log('drew assets/' + CARDS[k]);
  }
  await browser.close();
})();
